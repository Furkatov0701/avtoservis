import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const reply = await readFile(new URL('supabase/functions/_shared/bot-replies.js', root), 'utf8');
const edge = (await readFile(new URL('supabase/functions/_shared/telegram-edge.js', root), 'utf8')).replace("import { replyForUpdate } from './bot-replies.js';\n", '');
const bundle = '// Generated by npm run build:edge. Paste this entire file into the Supabase function editor.\n// Function name: telegram-bot. Secrets belong in Supabase Secrets, never in this file.\n\n' + reply + '\n' + edge + '\nDeno.serve(createEdgeHandler({ env: name => Deno.env.get(name) }));\n';
const target = new URL('supabase/dashboard/telegram-bot.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== bundle) throw new Error('Dashboard function is stale. Run npm run build:edge.');
  console.log('Dashboard function matches the tested source.');
} else {
  await mkdir(new URL('supabase/dashboard/', root), { recursive: true });
  await writeFile(target, bundle);
  console.log('Created supabase/dashboard/telegram-bot.ts (no credentials).');
}
